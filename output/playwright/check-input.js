async(page)=>{
  const assert=(condition,message)=>{if(!condition)throw new Error(message)};
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1280,height:720});
  await page.goto('http://127.0.0.1:5173/');
  await page.locator('.console-environment[data-boot=home]').waitFor();
  await page.mouse.move(2,2);
  for(let i=0;i<4;i++)await page.keyboard.press('ArrowLeft');
  await page.keyboard.press('End');
  await page.locator('[data-console-item=contributing][aria-current=true]').waitFor();
  await page.keyboard.press('Home');
  await page.locator('[data-console-item=profile][aria-current=true]').waitFor();
  await page.keyboard.press('t');
  const options=page.getByRole('dialog',{name:'Options for Profile'});
  await options.waitFor();
  await page.waitForFunction(()=>document.activeElement?.textContent.trim()==='Open');
  await page.keyboard.press('ArrowDown');
  assert(await page.locator('.console-destination-position.is-selected a').getAttribute('data-console-item')==='profile','Options moved background menu');
  await page.keyboard.press('End');
  assert((await page.locator('.console-option.is-selected').innerText())==='Information','Options End failed');
  await page.keyboard.press('Tab');
  assert((await page.locator('.console-option.is-selected').innerText())==='Open','Options Tab failed');
  await page.keyboard.press('Backspace');
  await options.waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.activeElement?.matches('[data-console-item=profile]'));
  await page.locator('[data-console-item=trophies]').click({button:'right'});
  await page.getByRole('dialog',{name:'Options for Trophies'}).waitFor();
  await page.locator('.console-options-dismiss').click({position:{x:20,y:300}});
  await page.locator('.console-options[data-open=false]').waitFor({state:'attached'});
  await page.getByRole('button',{name:'Search all destinations',exact:true}).click();
  const input=page.getByRole('textbox',{name:'Search destinations'});
  await input.fill('Protocol');await input.press('Enter');
  await page.locator('.console-application').waitFor();
  assert(page.url().includes('/protocols'),'Search keyboard navigation failed');
  await page.keyboard.press('Escape');
  await page.locator('.console-menu[data-hidden=false]').waitFor();
  await page.locator('[data-console-item=profile]').click();
  await page.locator('.console-application').waitFor();
  assert(page.url().includes('/profile'),'Mouse activated wrong row');
  await page.keyboard.press('Escape');
  await page.locator('.console-menu[data-hidden=false]').waitFor();
  await page.locator('.console-sound').click();
  await page.getByRole('dialog',{name:'Audio settings',exact:true}).waitFor();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.activeElement?.matches('.console-sound'));
  await page.setViewportSize({width:390,height:844});
  const controls=page.getByRole('navigation',{name:'Menu navigation',exact:true});
  assert(await controls.isVisible(),'Mobile controls missing');
  await page.getByRole('button',{name:'Next destination',exact:true}).click();
  await page.locator('[data-console-item=trophies][aria-current=true]').waitFor();
  await page.getByRole('button',{name:'Open selected destination',exact:true}).click();
  await page.locator('[data-testid=trophies]').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('.console-menu[data-hidden=false]').waitFor();
  await page.locator('.console-notice-toggle').click();
  await page.locator('.console-notice-list').waitFor();
  const before=await page.locator('.console-notice-list [aria-selected=true]').getAttribute('id');
  await page.mouse.move(300,350);await page.mouse.wheel(0,100);
  await page.waitForFunction(id=>document.querySelector('.console-notice-list [aria-selected=true]')?.id!==id,before);
  await page.getByRole('button',{name:'Open selected notification',exact:true}).click();
  await page.locator('.console-commit').waitFor();
  assert(await page.locator('.console-menu').isHidden(),'Background visible');
  await page.keyboard.press('Escape');await page.keyboard.press('Escape');
  await page.locator('.console-notice-toggle[data-open=false]').waitFor();
  const targets=await page.locator('.console-mobile-nav button, .console-help button, .console-search-toggle, .console-notice-toggle').evaluateAll(all=>all.map(e=>({name:e.getAttribute('aria-label'),w:e.getBoundingClientRect().width,h:e.getBoundingClientRect().height})));
  assert(targets.every(r=>r.w>=44&&r.h>=44),'Touch target smaller than 44px: '+JSON.stringify(targets));
  assert(!errors.length,errors.join('; '));
  return {keyboard:'pass',mouse:'pass',mobileControls:'pass',notificationWheel:'pass',focus:'restored',targets,errors};
}
