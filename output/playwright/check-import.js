async (page) => {
  const assert = (value,message) => { if(!value) throw new Error(message); };
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1280,height:720});
  await page.goto('http://127.0.0.1:5173/');
  await page.locator('.console-environment[data-boot=home]').waitFor();
  for(let i=0;i<4;i++) await page.keyboard.press('ArrowLeft');
  for(let i=0;i<6;i++) await page.keyboard.press('ArrowUp');
  for(let i=0;i<3;i++) await page.keyboard.press('ArrowDown');
  await page.locator('[data-console-item=github][aria-current=true]').waitFor();
  await page.keyboard.press('Enter');
  const dialog=page.getByRole('alertdialog');
  await dialog.waitFor();
  assert(await dialog.evaluate(el=>el.contains(document.activeElement)),'Dialog does not own keyboard focus');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  assert(page.context().pages().length===1,'Cancel opened an external tab');
  const selected=await page.locator('.console-destination-position.is-selected a').getAttribute('data-console-item');
  await page.reload();
  await page.locator('.console-environment[data-boot=home]').waitFor();
  assert(await page.locator('.console-destination-position.is-selected a').getAttribute('data-console-item')===selected,'Cursor not persisted');
  await page.goto('http://127.0.0.1:5173/theme');
  await page.locator('[data-testid=theme-settings]').waitFor();
  const palette=()=>page.evaluate(async()=>{
    const loaded=performance.getEntriesByType('resource').find(e=>new URL(e.name).pathname==='/src/xmb/palette.ts');
    const m=await import(loaded.name);
    return {stored:m.selectedTheme(),colors:[...m.monthlyPalette()]};
  });
  const initial=await palette();
  const target=initial.stored===0?1:0;
  const name=target===0?'Ice':'Violet';
  const theme=page.getByRole('button',{name:'Atmosphere '+name,exact:true});
  await theme.focus();
  const preview=await palette();
  assert(preview.stored===initial.stored,'Preview changed saved theme');
  assert(JSON.stringify(preview.colors)!==JSON.stringify(initial.colors),'Preview did not change palette');
  await page.keyboard.press('Escape');
  await page.locator('[data-testid=theme-settings]').waitFor({state:'hidden'});
  const reverted=await palette();
  assert(reverted.stored===initial.stored && JSON.stringify(reverted.colors)===JSON.stringify(initial.colors),'Preview did not revert');
  await page.goto('http://127.0.0.1:5173/theme');
  await theme.click();
  assert((await palette()).stored===target,'Theme not confirmed');
  await page.goto('http://127.0.0.1:5173/trophies');
  await page.locator('[data-testid=trophies]').waitFor();
  const trophy=page.getByRole('button',{name:'Atmosphere, unlocked',exact:true});
  assert(await trophy.count()===1,'Theme trophy not earned');
  assert(await page.getByRole('button',{name:'Hidden trophy, locked',exact:true}).count()===1,'Hidden trophy exposed');
  assert(errors.length===0,errors.join('; '));
  return {cursor:'persisted',dialog:'cancelled without navigation',preview:'reverts',theme:'saved',trophies:'earned and persistent',errors};
}
