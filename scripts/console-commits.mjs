#!/usr/bin/env node
/**
 * Turns the repository history into the console's notification feed.
 *
 * The XMB carries a notification column, and on this console the entries in
 * it are the project's own commits: the same history a reader would find on
 * the repository page, frozen at build time so the site stays a static,
 * offline document with no runtime calls.
 *
 * The output is a TypeScript module under src/data/. It is regenerated before
 * every build, so the notifications always describe the checkout that produced
 * them. When git cannot be reached (a source tarball, a sandbox without the
 * repository) the existing file is left untouched rather than emptied.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const target = resolve(root, "src/data/commits.generated.ts");

/** How many commits the notification column can hold. */
const LIMIT = 14;
/** Field separator; a control character cannot appear in a commit subject. */
const SEP = "\u001f";
const FIELDS = ["%H", "%h", "%an", "%aI", "%s"].join(SEP);

/** Conventional-commit prefixes, plus the merge subjects Git writes itself. */
const KINDS = ["feat", "fix", "docs", "ci", "test", "perf", "build", "refactor", "chore", "style", "revert"];

function kindOf(subject) {
  if (/^Merge pull request/.test(subject)) return "merge";
  if (/^Merge branch/.test(subject)) return "merge";
  const match = /^([a-z]+)(\([^)]*\))?!?:/.exec(subject);
  if (!match) return "other";
  const kind = match[1];
  return KINDS.includes(kind) ? kind : "other";
}

function readHistory() {
  try {
    const raw = execFileSync("git", ["log", `-${LIMIT}`, `--pretty=format:${FIELDS}`], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 4 * 1024 * 1024,
    });
    return raw
      .split("\n")
      .filter((line) => line.length > 0)
      .map((line) => {
        const [sha, short, author, date, subject] = line.split(SEP);
        return { sha, short, author, date, subject, kind: kindOf(subject) };
      })
      .filter((commit) => commit.sha && commit.subject);
  } catch {
    return [];
  }
}

function render(commits) {
  const rows = commits
    .map((c) =>
      [
        "  {",
        `    sha: ${JSON.stringify(c.sha)},`,
        `    short: ${JSON.stringify(c.short)},`,
        `    subject: ${JSON.stringify(c.subject)},`,
        `    author: ${JSON.stringify(c.author)},`,
        `    date: ${JSON.stringify(c.date)},`,
        `    kind: ${JSON.stringify(c.kind)},`,
        "  },",
      ].join("\n"),
    )
    .join("\n");
  return `/**
 * The console's notification feed: the repository history, read at build time.
 *
 * Generated by scripts/console-commits.mjs — do not edit by hand.
 */
export interface CommitNotice {
  /** Full object name. */
  sha: string;
  /** Abbreviated object name, as the console shows it. */
  short: string;
  /** Commit subject line. */
  subject: string;
  /** Author name at commit time. */
  author: string;
  /** Author date, ISO 8601. */
  date: string;
  /** Conventional-commit kind, or "merge" for Git's own merge subjects. */
  kind: string;
}

export const COMMIT_NOTICES: CommitNotice[] = [
${rows}
];
`;
}

const commits = readHistory();
if (commits.length === 0) {
  console.warn("[console-commits] no git history available; keeping the existing notification feed");
  process.exit(0);
}
writeFileSync(target, render(commits));
console.log(`[console-commits] ${commits.length} notifications written to src/data/commits.generated.ts`);
