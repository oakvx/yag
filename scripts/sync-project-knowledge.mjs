import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

// Fetch explicitly first. Never merge, switch branches or rewrite the worktree.
const check = process.argv.includes('--check');
const ref = process.argv.find(arg => arg.startsWith('--ref='))?.slice(6) ?? 'origin/main';
const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 }).replace(/\r\n/g, '\n');
const revision = git('rev-parse', `${ref}^{commit}`).trim();
const file = path => git('show', `${revision}:${path}`);
const excerpts = {};
function extract(id, path, start, end) {
  const lines = file(path).trimEnd().split('\n');
  const first = start ? lines.findIndex(line => line.includes(start)) : 0;
  const last = typeof end === 'number' ? first + end : end ? lines.findIndex((line, index) => index > first && line.includes(end)) : lines.length;
  if (first < 0 || last <= first || last > lines.length) throw Error(`Source markers changed: ${id}`);
  excerpts[id] = { code: lines.slice(first, last).join('\n'), startLine: first + 1, endLine: last,
    href: `https://github.com/oakvx/yag/blob/${revision}/${path}#L${first + 1}-L${last}` };
}
extract('main-c', 'host/src/main.c');
extract('yag-h', 'host/include/yag.h', 'const char *bind, *port', 'time_t rate_windows');
extract('server-auth', 'host/src/http/server.c', '/* Authenticate from headers BEFORE', '/* Send 100');
extract('server-routes-redact', 'host/src/http/server.c', 'else if(!strcmp(uri,"/api/routes")', 17);
extract('config-routes', 'host/src/core/config.c', 'const yag_config *config_for_model(', 11);
extract('openai-upstream', 'host/src/inference/openai.c', 'int upstream_for_model(', 'static size_t proxy_write(');
extract('responses-adapter', 'host/src/protocols/openai_responses/request.c', 'const char *const top[]', 'yyjson_val *include=');
extract('anthropic-adapter', 'host/src/protocols/anthropic/messages.c', 'static int thinking_valid(', '/* The gateway has no reasoning blocks');
extract('cmake-build', 'CMakeLists.txt', null, 13);
extract('tests-contract', 'tests/anthropic.py', '    def test_streaming_text_event_order(', '    def test_streaming_tool_blocks(');
extract('adaptive-scheduler', 'host/src/core/scheduler.c', 'static void refresh_adaptive_capacity(', 'static int has_capacity(');
extract('admin-audit', 'host/src/core/admin_audit.c');
extract('pool-admission', 'host/src/inference/openai.c', 'static int pool_choose_locked(', 'static int pool_choose(');
const snapshot = {
  revision, commitDate: git('show', '-s', '--format=%cI', revision).trim(),
  ctestSuites: (file('CMakeLists.txt').match(/add_test\(NAME /g) ?? []).length,
  excerpts,
};
const target = 'src/data/project-snapshot.generated.ts';
const output = '// Generated by scripts/sync-project-knowledge.mjs; source bytes and line ranges come from Git.\nexport const PROJECT_SNAPSHOT = '+JSON.stringify(snapshot, null, 2)+';\n';
if (check) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw Error('Project snapshot is out of date. Run the sync script and review the prose.');
  console.log(`${Object.keys(excerpts).length} exact source excerpts verified at ${revision.slice(0,7)}; ${snapshot.ctestSuites} registered CTest suites.`);
} else {
  writeFileSync(target, output.replace(/\n/g, '\r\n'));
  console.log(`Updated project snapshot at ${revision.slice(0,7)}. Review descriptions when source changes.`);
}
